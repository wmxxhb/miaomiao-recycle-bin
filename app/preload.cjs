const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('pet', {
  state: () => ipcRenderer.invoke('state'),
  choose: value => ipcRenderer.invoke('choose', value),
  configure: value=>ipcRenderer.invoke('configure',value),
  openStudio:()=>ipcRenderer.invoke('open-studio'),
  feedFiles: files => ipcRenderer.invoke('feed', Array.from(files, file => webUtils.getPathForFile(file)).filter(Boolean)),
  onState: callback => { ipcRenderer.on('state', (_event, value) => callback(value)); },
  dragBegin: () => ipcRenderer.invoke('drag-begin'),
  dragCancel: () => ipcRenderer.send('drag-cancel'),
  quit: () => ipcRenderer.send('quit'),
  hide: () => ipcRenderer.send('hide'),
  dialogueOpen:()=>ipcRenderer.invoke('dialogue-open'),
  dialogueClose:kind=>ipcRenderer.send('dialogue-close',kind),
  dialogueMeasure:(kind,height)=>ipcRenderer.send('dialogue-measure',kind,height),
  dialogueAnchors:value=>ipcRenderer.send('dialogue-anchors',value),
  onDialogueContent:callback=>ipcRenderer.on('dialogue-content',(_event,value)=>callback(value)),
  onDialogueLayout:callback=>ipcRenderer.on('dialogue-layout',(_event,value)=>callback(value)),
  onDialogueInputState:callback=>ipcRenderer.on('dialogue-input-state',(_event,value)=>callback(value)),
  onDialogueNotice:callback=>ipcRenderer.on('dialogue-notice',(_event,value)=>callback(value)),
  onDialogueFocus:callback=>ipcRenderer.on('dialogue-focus',(_event,value)=>callback(value)),
  aiConfig:()=>ipcRenderer.invoke('ai-config'),
  aiSave:value=>ipcRenderer.invoke('ai-save',value),
  aiTest:value=>ipcRenderer.invoke('ai-test',value),
  aiModels:value=>ipcRenderer.invoke('ai-models',value),
  aiState:()=>ipcRenderer.invoke('ai-state'),
  aiSend:value=>ipcRenderer.invoke('ai-send',value),
  aiStop:()=>ipcRenderer.invoke('ai-stop'),
  aiProvider:id=>ipcRenderer.invoke('ai-provider',id),
  aiNew:()=>ipcRenderer.invoke('ai-new'),
  aiSelect:id=>ipcRenderer.invoke('ai-select',id),
  aiClear:()=>ipcRenderer.invoke('ai-clear'),
  aiDelete:()=>ipcRenderer.invoke('ai-delete'),
  aiExport:()=>ipcRenderer.invoke('ai-export'),
  aiCopy:id=>ipcRenderer.invoke('ai-copy',id),
  onAIConfig:callback=>{const handler=(_event,value)=>callback(value);ipcRenderer.on('ai-config',handler);return()=>ipcRenderer.removeListener('ai-config',handler);},
  onAIUpdate:callback=>{const handler=(_event,value)=>callback(value);ipcRenderer.on('ai-update',handler);return()=>ipcRenderer.removeListener('ai-update',handler);},
  onAIReply:callback=>{const handler=(_event,value)=>callback(value);ipcRenderer.on('ai-reply',handler);return()=>ipcRenderer.removeListener('ai-reply',handler);},
});
